-- Sin policies sobre storage.objects: anon y authenticated no pueden listar, leer ni escribir. El servidor del panel emite
-- URLs firmadas (subida y lectura de 1 h) con service_role. Límite y tipos los hace cumplir el propio bucket.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'track-adjuntos', 'track-adjuntos', false, 26214400,
  array['image/png', 'image/jpeg', 'image/webp', 'image/gif', 'video/mp4', 'video/quicktime', 'video/webm']
)
on conflict (id) do update
  set public = false,
      file_size_limit = excluded.file_size_limit,
