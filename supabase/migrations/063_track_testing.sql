-- Códigos automáticos (T-01, B-01, U-01) y updated_at ------------------------------------------------------------------
-- Si el insert ya trae código (el seed con los T-xx de la planilla) se respeta y el contador se corre para no repetirlo.
create or replace function public.track_asignar_codigo()
returns trigger
language plpgsql
set search_path = public
as $$
declare
  v_prefijo text := tg_argv[0];
  v_seq regclass := tg_argv[1]::regclass;
  v_n bigint;
begin
  if new.codigo is null or new.codigo = '' then
    new.codigo := v_prefijo || '-' || lpad(nextval(v_seq)::text, 2, '0');
  elsif new.codigo ~ ('^' || v_prefijo || '-[0-9]+$') then
    v_n := substring(new.codigo from '[0-9]+$')::bigint;
    if v_n > coalesce((select last_value from pg_sequences where schemaname = 'public' and sequencename = tg_argv[1]), 0) then
      perform setval(v_seq, v_n);
    end if;
  end if;
  return new;
end $$;

create or replace function public.track_tocar()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists track_casos_codigo on public.track_casos;
create trigger track_casos_codigo before insert on public.track_casos
  for each row execute function public.track_asignar_codigo('T', 'track_casos_codigo_seq');
