-- Casos ----------------------------------------------------------------------------------------------------------------
create table if not exists public.track_casos (
  id bigint generated by default as identity primary key,
  codigo text not null unique,
  area text not null default 'General' check (char_length(area) between 1 and 60),
  funcionalidad text not null default '' check (char_length(funcionalidad) <= 200),
  prioridad text not null default 'Media' check (prioridad in ('Alta', 'Media', 'Baja')),
  precondicion text not null default '' check (char_length(precondicion) <= 2000),
  pasos text not null default '' check (char_length(pasos) <= 4000),
  esperado text not null default '' check (char_length(esperado) <= 2000),
  posicion int not null default 0,
  archivado boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Rondas y asignaciones ------------------------------------------------------------------------------------------------
create table if not exists public.track_rondas (
  id bigint generated by default as identity primary key,
  nombre text not null check (char_length(nombre) between 1 and 120),
  version_app text not null default '' check (char_length(version_app) <= 40),
  desde date not null default current_date,
  hasta date,
  estado text not null default 'activa' check (estado in ('activa', 'cerrada')),
  notas text not null default '' check (char_length(notas) <= 2000),
  creada_por text not null check (char_length(creada_por) between 3 and 320),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.track_asignaciones (
  id bigint generated by default as identity primary key,
  ronda_id bigint not null references public.track_rondas(id) on delete cascade,
  caso_id bigint not null references public.track_casos(id) on delete cascade,
  admin_email text check (admin_email is null or char_length(admin_email) between 3 and 320),
  dispositivo text not null default '' check (char_length(dispositivo) <= 120),
  created_at timestamptz not null default now()
);

